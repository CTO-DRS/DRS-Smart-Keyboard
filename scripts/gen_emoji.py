def main():
    import os
    out_dir = os.path.join(os.path.dirname(__file__), "..", "DRSKeyboard", "app", "src", "main", "assets", "dict")
    os.makedirs(out_dir, exist_ok=True)
    n = 0
    with open(os.path.join(out_dir, "emoji.txt"), "w", encoding="utf-8") as f:
        for cat, blob in E.items():
            for em in blob.split():
                f.write(f"{cat}\t{em}\n")
                n += 1
    print(f"emoji.txt: {n} emoji")


if __name__ == "__main__":
    main()
