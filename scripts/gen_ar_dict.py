def clean(w: str) -> str:
    # remove stray latin/digits/dupes, normalize alef variants stay as typed
    w = w.strip().strip("،")
    return w if w and not any(c.isdigit() or ("a" <= c.lower() <= "z") for c in w) else ""


# Conservative clitics — every combination below yields real Arabic words.
PREFIXES = [("وال", 0.35), ("فال", 0.30), ("بال", 0.40), ("لل", 0.35), ("ال", 0.55),
            ("و", 0.45), ("ف", 0.30), ("ب", 0.35), ("ل", 0.28), ("ك", 0.22)]
SUFFIXES = [("ات", 0.32), ("ون", 0.24), ("ين", 0.24), ("ية", 0.30), ("ها", 0.24),
            ("هم", 0.18), ("نا", 0.16), ("ه", 0.24), ("ك", 0.20), ("ي", 0.28), ("ة", 0.32)]
COMBOS = [("ال", "ات", 0.30), ("ال", "ي", 0.28), ("وال", "ة", 0.24), ("وال", "ات", 0.22),
          ("وال", "ين", 0.20), ("بال", "ة", 0.20), ("فال", "ة", 0.18)]

NO_SUFFIX_END = ("ة", "ى", "ا", "ي", "ه", "ات", "ون", "ين")


def main():
    import os
    out_dir = os.path.join(os.path.dirname(__file__), "..", "DRSKeyboard", "app", "src", "main", "assets", "dict")
    os.makedirs(out_dir, exist_ok=True)
    seen = set()
    rows = []
    rank_f = 0.0

    def add(w, damp):
        nonlocal rank_f
        if not w or len(w) < 2 or w in seen:
            return
        seen.add(w)
        freq = max(int(60000 * (0.99930 ** rank_f) * damp), 45)
        rows.append((w, freq))
        rank_f += 0.85

    for raw in BASE:
        w = clean(raw)
        if not w:
            continue
        add(w, 1.0)
        if len(w) < 3:
            continue
        for p, f in PREFIXES:
            add(p + w, f)
        if not w.endswith(NO_SUFFIX_END):
            for s, f in SUFFIXES:
                add(w + s, f)
        if len(w) >= 4:
            for p, s, f in COMBOS:
                if s == "ات" or not w.endswith(NO_SUFFIX_END):
                    add(p + w + s, f)

    rows.sort(key=lambda r: -r[1])
    with open(os.path.join(out_dir, "ar_freq.txt"), "w", encoding="utf-8") as f:
        for w, freq in rows:
            f.write(f"{w}\t{freq}\n")
    print(f"ar_freq.txt: {len(rows)} words, top={rows[0][1]}, last={rows[-1][1]}")


if __name__ == "__main__":
    main()
