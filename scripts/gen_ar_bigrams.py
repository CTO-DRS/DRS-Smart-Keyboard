MORPH = {"كتاب": ["كتابي", "كتابه"], "بيت": ["بيتي", "بيته"], "عمل": ["عملي", "عمله"]}


def main():
    out_dir = os.path.join(os.path.dirname(__file__), "..", "DRSKeyboard", "app", "src", "main", "assets", "dict")
    os.makedirs(out_dir, exist_ok=True)
    rows, seen, rank = [], set(), 0
    for line in PAIRS.split("\n"):
        toks = line.split()
        for i in range(len(toks) - 1):
            a, b = toks[i], toks[i + 1]
            if not a or not b:
                continue
            key = (a, b)
            if key in seen:
                continue
            seen.add(key)
            rows.append((a, b, max(4000 - rank * 7, 12)))
            rank += 1
    for w, vs in MORPH.items():
        for v in vs:
            rows.append((w, v, 900))
    with open(os.path.join(out_dir, "ar_bigrams.txt"), "w", encoding="utf-8") as f:
        for a, b, c in rows:
            f.write(f"{a}\t{b}\t{c}\n")
    print(f"ar_bigrams.txt: {len(rows)} pairs")


if __name__ == "__main__":
    main()
